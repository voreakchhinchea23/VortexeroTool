/**
 * Get the color scheme for any tool by its ID and fallback to category.
 */
export function getToolColor(toolId: string, category?: ToolCategory): ToolColorScheme {
  if (TOOL_COLOR_DEFINITIONS[toolId]) {
    return TOOL_COLOR_DEFINITIONS[toolId];
  }

  // Fallback to Category theme if specific tool not defined
  const cat = category && CATEGORY_COLORS[category] ? CATEGORY_COLORS[category] : CATEGORY_COLORS.all;
  return {
    id: toolId,
    name: cat.name,
    accentHex: cat.accentHex,
    gradient: cat.gradient,
    iconColor: cat.iconColor,
    iconBg: cat.bgLight + ' ' + cat.bgDark,
    iconBorder: cat.borderLight + ' ' + cat.borderDark,
    iconHoverGradient: `group-hover:bg-gradient-to-tr group-hover:${cat.gradient} group-hover:text-white`,
    cardBorderHover: 'hover:border-brand-500/50',
    cardGlowHover: 'hover:shadow-brand-500/15',
    vibrantCardBg: 'bg-gradient-to-br from-slate-900/90 via-slate-900/90 to-slate-900/95',
    vibrantBorder: 'border-slate-800/80',
    vibrantGlow: 'shadow-[0_4px_20px_-4px_rgba(0,0,0,0.3)]',
    tagBgHover: 'group-hover:bg-brand-50 dark:group-hover:bg-brand-950/40',
    tagTextHover: 'group-hover:text-brand-600 dark:group-hover:text-brand-300',
    badgeBg: 'bg-brand-500/10 dark:bg-brand-500/20',
    badgeText: 'text-brand-600 dark:text-brand-300',
    badgeBorder: 'border-brand-500/30',
  };
}

/**
 * Get category color scheme
 */
export function getCategoryColor(category: ToolCategory): CategoryColorScheme {
  return CATEGORY_COLORS[category] || CATEGORY_COLORS.all;
}
